// The two places every test in this file writes, and the exact block bytes
// SetLocation is expected to emit for each. Hard-coding the expected block
// keeps the merge assertions honest: a test that regenerated the block with
// the same code under test could not see a formatting regression.
var (
	berlin = location.PlaceInfo{
		Name: "Berlin", Country: "DE",
		Lat: 52.5244, Lon: 13.4105, TZ: "Europe/Berlin",
	}
	tokyo = location.PlaceInfo{
		Name: "Tokyo", Country: "JP",
		Lat: 35.6762, Lon: 139.6503, TZ: "Asia/Tokyo",
	}
)

// versionLine is what every Sextile-managed preferences.yaml now opens with
// : the write owns a `version:` block as well as `location:`, and
// prepends it when the file does not already declare a generation. Every
// byte-exact expectation below therefore carries it. Hard-coded here for the
// same reason the location blocks are: an expectation generated by the code
// under test could not see a regression.
const versionLine = "version: 1\n"

const (
	berlinBlock = "location:\n" +
		"  name: Berlin\n" +
		"  country: DE\n" +
		"  lat: 52.5244\n" +
		"  lon: 13.4105\n" +
		"  tz: Europe/Berlin\n"
	tokyoBlock = "location:\n" +
		"  name: Tokyo\n" +
		"  country: JP\n" +
		"  lat: 35.6762\n" +
		"  lon: 139.6503\n" +
		"  tz: Asia/Tokyo\n"
)

// prefPath points PreferencesPath() at a temp dir and returns the file path
// it resolves to. The file itself is not created.
func prefPath(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	t.Setenv("XDG_CONFIG_HOME", dir)
	return filepath.Join(dir, "sextile", "preferences.yaml")
}

func seedPreferences(t *testing.T, path, body string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatalf("mkdir: %v", err)
	}
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		t.Fatalf("seed: %v", err)
	}
}

func readPreferences(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read back: %v", err)
	}
	return string(b)
}

func diffText(got, want string) string {
	return "\n--- got ---\n" + got + "\n--- want ---\n" + want + "\n"
}

// C1: every line outside the location: block survives byte-for-byte, even in
// blocks store has no parser for.
func TestSetLocationPreservesForeignBlocks(t *testing.T) {
	path := prefPath(t)
	head := "# sextile preferences\n" +
		"theme:\n" +
		"  accent: teal\n" +
		"\n" +
		// `location :` is not the block store owns: the readers start only
		// on the exact `location:` prefix, so this one is invisible to them
		// and must survive the write like any other foreign block.
		"location :\n" +
		"  note: keep me\n" +
		"\n"
	tail := "\n" +
		"weird: [1, 2, 3]\n" +
		"nested:\n" +
		"  deep:\n" +
		"    - a\n" +
		"    - b\n"
	seedPreferences(t, path, head+berlinBlock+tail)

	if err := SetLocation(tokyo); err != nil {
		t.Fatalf("SetLocation: %v", err)
	}
	got := readPreferences(t, path)
	want := versionLine + head + tokyoBlock + tail
	if got != want {
		t.Errorf("foreign blocks not preserved:%s", diffText(got, want))
	}
}

// C2: a rewritten block keeps its position among the file's other blocks.
func TestSetLocationKeepsBlockPosition(t *testing.T) {
	path := prefPath(t)
	head := "theme:\n  accent: teal\n"
	tail := "logging:\n  level: debug\n"
	seedPreferences(t, path, head+berlinBlock+tail)

	if err := SetLocation(tokyo); err != nil {
		t.Fatalf("SetLocation: %v", err)
	}
	got := readPreferences(t, path)
	if want := versionLine + head + tokyoBlock + tail; got != want {
		t.Fatalf("block moved:%s", diffText(got, want))
	}
	order := topLevelOrder(got)
	wantOrder := []string{"version", "theme", "location", "logging"}
	if strings.Join(order, ",") != strings.Join(wantOrder, ",") {
		t.Errorf("top-level order = %v, want %v", order, wantOrder)
	}
}

// topLevelOrder lists the keys of the file's top-level blocks in order. It is
// deliberately a separate, dumber reimplementation of the production scanner:
// the test must not inherit the code under test's idea of a block boundary.
func topLevelOrder(body string) []string {
	var out []string
	for _, line := range strings.Split(body, "\n") {
		if line == "" || line[0] == ' ' || line[0] == '\t' || line[0] == '#' {
			continue
		}
		if idx := strings.Index(line, ":"); idx > 0 {
			out = append(out, line[:idx])
		}
	}
	return out
}

// C3: with no location: block present, the block is appended and nothing that
// was already there moves.
func TestSetLocationAppendsWhenAbsent(t *testing.T) {
	path := prefPath(t)
	before := "theme:\n  accent: teal\nlogging:\n  level: debug\n"
	seedPreferences(t, path, before)

	if err := SetLocation(berlin); err != nil {
		t.Fatalf("SetLocation: %v", err)
	}
	got := readPreferences(t, path)
	if want := versionLine + before + berlinBlock; got != want {
		t.Errorf("append mangled the file:%s", diffText(got, want))
	}
}

// C3, again: a key that merely looks like the owned one is not the owned one,
// so the real block is still appended and the lookalike stays put.
func TestSetLocationAppendsWhenAbsentPastLookalike(t *testing.T) {
	path := prefPath(t)
	before := "location :\n  note: keep me\n\"location\": quoted\n"
	seedPreferences(t, path, before)

	if err := SetLocation(berlin); err != nil {
		t.Fatalf("SetLocation: %v", err)
	}
	got := readPreferences(t, path)
	if want := versionLine + before + berlinBlock; got != want {
		t.Errorf("lookalike keys were treated as the owned block:%s", diffText(got, want))
	}
}

// C4: with no file at all, the parent directory is created and the result is
// the block alone.
func TestSetLocationCreatesFile(t *testing.T) {
	path := prefPath(t)
	if _, err := os.Stat(path); !os.IsNotExist(err) {
		t.Fatalf("precondition: preferences.yaml should not exist, stat err = %v", err)
	}
	if err := SetLocation(berlin); err != nil {
		t.Fatalf("SetLocation: %v", err)
	}
	if want, got := versionLine+berlinBlock, readPreferences(t, path); got != want {
		t.Errorf("fresh file:%s", diffText(got, want))
	}
}

