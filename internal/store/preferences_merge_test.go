// C7: a failure anywhere in the write leaves the target file untouched.
func TestSetLocationAtomicOnFailure(t *testing.T) {
	requireUnprivileged(t)
	path := prefPath(t)
	before := "theme:\n  accent: teal\n" + berlinBlock
	seedPreferences(t, path, before)

	dir := filepath.Dir(path)
	if err := os.Chmod(dir, 0o555); err != nil {
		t.Fatalf("chmod dir: %v", err)
	}
	t.Cleanup(func() { _ = os.Chmod(dir, 0o755) })

	if err := SetLocation(tokyo); err == nil {
		t.Fatal("expected an error when the config directory is not writable")
	}
	if got := readPreferences(t, path); got != before {
		t.Errorf("failed write changed the file:%s", diffText(got, before))
	}
}

// C8: callers keep compiling — the signature and error contract are frozen.
func TestSetLocationSignatureUnchanged(t *testing.T) {
	var fn func(location.PlaceInfo) error = SetLocation
	prefPath(t)
	if err := fn(berlin); err != nil {
		t.Fatalf("SetLocation must still return a plain error, got %v", err)
	}
}

// C9: an unreadable existing file is an error, not an excuse to start over.
func TestSetLocationRefusesUnreadableFile(t *testing.T) {
	requireUnprivileged(t)
	path := prefPath(t)
	before := "theme:\n  accent: teal\n" + berlinBlock
	seedPreferences(t, path, before)
	if err := os.Chmod(path, 0o000); err != nil {
		t.Fatalf("chmod file: %v", err)
	}
	t.Cleanup(func() { _ = os.Chmod(path, 0o644) })

	if err := SetLocation(tokyo); err == nil {
		t.Fatal("expected an error when the existing file cannot be read")
	}
	if err := os.Chmod(path, 0o644); err != nil {
		t.Fatalf("chmod back: %v", err)
	}
	if got := readPreferences(t, path); got != before {
		t.Errorf("unreadable file was replaced:%s", diffText(got, before))
	}
}

// C10: store does not adjudicate malformed input — the first block is the one
// it owns, the second is somebody else's problem and is carried through.
func TestSetLocationDuplicateBlocks(t *testing.T) {
	path := prefPath(t)
	tail := "theme:\n  accent: teal\n" +
		"location:\n  name: Ghost\n  tz: UTC\n"
	seedPreferences(t, path, berlinBlock+tail)

	if err := SetLocation(tokyo); err != nil {
		t.Fatalf("SetLocation: %v", err)
	}
	got := readPreferences(t, path)
	if want := versionLine + tokyoBlock + tail; got != want {
		t.Errorf("duplicate block handling:%s", diffText(got, want))
	}
}

// C11: an unterminated final line gets a separator, never a splice.
func TestSetLocationNoTrailingNewline(t *testing.T) {
	t.Run("append", func(t *testing.T) {
		path := prefPath(t)
		seedPreferences(t, path, "theme:\n  accent: teal")

		if err := SetLocation(berlin); err != nil {
			t.Fatalf("SetLocation: %v", err)
		}
		got := readPreferences(t, path)
		want := versionLine + "theme:\n  accent: teal\n" + berlinBlock
		if got != want {
			t.Fatalf("append after unterminated line:%s", diffText(got, want))
		}
		if strings.Contains(got, "teallocation") {
			t.Error("two lines were joined")
		}
		if _, ok := Location(); !ok {
			t.Error("merged file no longer parses")
		}
	})

	t.Run("replace", func(t *testing.T) {
		path := prefPath(t)
		seedPreferences(t, path, "theme:\n  accent: teal\nlocation:\n  name: Old\n  tz: UTC")

		if err := SetLocation(berlin); err != nil {
			t.Fatalf("SetLocation: %v", err)
		}
		got := readPreferences(t, path)
		want := versionLine + "theme:\n  accent: teal\n" + berlinBlock
		if got != want {
			t.Fatalf("replace of unterminated block:%s", diffText(got, want))
		}
		if _, ok := Location(); !ok {
			t.Error("merged file no longer parses")
		}
	})
}

// C12: an empty file is indistinguishable from a fresh one.
func TestSetLocationEmptyFile(t *testing.T) {
	path := prefPath(t)
	seedPreferences(t, path, "")

	if err := SetLocation(berlin); err != nil {
		t.Fatalf("SetLocation: %v", err)
	}
	if want := versionLine + berlinBlock; readPreferences(t, path) != want {
		t.Errorf("empty file:%s", diffText(readPreferences(t, path), want))
	}
}

// requireUnprivileged skips permission-based tests when the process can
// ignore file modes, which is the normal case inside a root container.
func requireUnprivileged(t *testing.T) {
	t.Helper()
	if os.Geteuid() == 0 {
		t.Skip("running as root: file modes do not restrain this process")
	}
}

// S4a A23: `, c d` saves the default city and nothing else. Every byte outside
// the location: block survives, a `frame:` block still holding the retired
// `base: cursor` included, with its comments, its ordering and the blocks the
// store has no parser for.
func TestSaveCityKeepsForeignLines(t *testing.T) {
	path := prefPath(t)
	head := versionLine +
		"# my sextile preferences\n" +
		"frame:\n" +
		"  houses: koch   # my houses\n" +
		"  base: cursor\n" +
		"  zodiac: tropical\n" +
		"\n"
	tail := "\n" +
		"clock:\n" +
		"  format: 24h\n" +
		"# trailing note\n"
	seedPreferences(t, path, head+berlinBlock+tail)

	if err := SetLocation(tokyo); err != nil {
		t.Fatalf("SetLocation: %v", err)
	}
	if got, want := readPreferences(t, path), head+tokyoBlock+tail; got != want {
		t.Errorf("bytes outside location: changed:%s", diffText(got, want))
	}
	// The frame block still reads as it did, base: cursor ignored.
	if cfg := Frame(); !cfg.HousesPresent || cfg.Houses != "koch" || !cfg.ZodiacPresent {
		t.Errorf("Frame() after the save = %+v", cfg)
	}
}
